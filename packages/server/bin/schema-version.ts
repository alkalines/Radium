import { readMigrationFiles } from "drizzle-orm/migrator";
import { MIGRATIONS_FOLDER } from "../src/db/migrate";

/**
 * Writes `src/db/schema-version.ts`: the newest migration this build expects the database to
 * have. Runs after `drizzle-kit generate` (`bun run db:generate`); CI regenerates and fails on a
 * diff, so the constant cannot drift from `drizzle/`.
 */
const newest = readMigrationFiles({ migrationsFolder: MIGRATIONS_FOLDER }).at(-1)?.name;
if (!newest) {
  throw new Error("No migrations in drizzle/");
}

await Bun.write(
  new URL("../src/db/schema-version.ts", import.meta.url),
  `// Generated by \`bun run db:generate\` (bin/schema-version.ts). Do not edit.

/** Newest migration this build was generated with; the server refuses a database without it. */
export const SCHEMA_VERSION = ${JSON.stringify(newest)};
`,
);
console.log(`SCHEMA_VERSION = ${newest}`);
